#!/usr/bin/env node
// guards — install and configure one guard engine across every harness.
//
//   guards init                      write a starter rule set
//   guards install [harness...]      wire the engine into the harnesses
//   guards uninstall [harness...]
//   guards status
//   guards rules
//   guards check --harness X --tool T --args '{...}'

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { evaluate } from './engine.js';
import { defaultConfigPath, loadConfig } from './rules.js';
import { HARNESSES } from './normalize.js';
import { add, buildRule, describeRule, remove, snapshot, toggle } from './manage.js';
import { detectAll } from './detect.js';
import { STARTER_RULES } from './starter.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const HOOK_ENTRY = path.join(HERE, 'guard-hook.js');
const PI_ENTRY = path.join(HERE, 'adapters', 'pi.js');
const SENTINEL = 'simple-llm-guards';

const GREEN = '\x1b[32m';
const DIM = '\x1b[2m';
const RESET = '\x1b[0m';

const home = os.homedir();
const PATHS = {
  pi: path.join(home, '.pi', 'agent', 'extensions', `${SENTINEL}.js`),
  omp: path.join(home, '.omp', 'agent', 'extensions', `${SENTINEL}.ts`),
  claude: path.join(home, '.claude', 'settings.json'),
  copilot: path.join(home, '.copilot', 'hooks', `${SENTINEL}.json`),
  gemini: path.join(home, '.gemini', 'settings.json'),
  agy: path.join(home, '.gemini', 'config', 'hooks.json'),
};

const ALIASES = {
  'claude-code': 'claude',
  'claude_code': 'claude',
  claudecode: 'claude',
  'copilot-cli': 'copilot',
  copilotcli: 'copilot',
  'gemini-cli': 'gemini',
  geminicli: 'gemini',
  antigravity: 'agy',
  ohmypi: 'omp',
  oh_my_pi: 'omp',
};

/** `node /abs/guard-hook.js --harness claude` — quoted, no shell tricks. */
function hookCommand(harness) {
  return `"${process.execPath}" "${HOOK_ENTRY}" --harness ${harness}`;
}

function readJson(file, fallback) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); }
  catch { return fallback; }
}

function writeJson(file, value, { dryRun }) {
  const text = JSON.stringify(value, null, 2) + '\n';
  if (dryRun) return text;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file)) fs.copyFileSync(file, `${file}.bak`);
  fs.writeFileSync(file, text);
  return text;
}

/** Antigravity keys its hooks by name, so guards owns exactly one key. */
function agyHookDefinition() {
  return {
    enabled: true,
    PreToolUse: [{ matcher: '*', hooks: [{ type: 'command', command: hookCommand('agy'), timeout: 10 }] }],
  };
}

/** The single hook entry guards owns inside a harness settings file. */
function guardsGroup(harness) {
  const command = hookCommand(harness);
  if (harness === 'gemini') return { hooks: [{ type: 'command', command, timeout: 10 }] };
  return { matcher: '*', hooks: [{ type: 'command', command, timeout: 10 }] };
}

function isOurs(entry) {
  return JSON.stringify(entry ?? '').includes(SENTINEL);
}

function normalizeName(name) {
  const key = String(name).toLowerCase();
  return ALIASES[key] ?? key;
}

// --- installers -------------------------------------------------------------
// Each one either rewrites a file we own (pi, omp, copilot, agy) or merges a
// single entry into a shared settings file (claude, gemini), always keeping a .bak.

const INSTALLERS = {
  pi: {
    label: 'pi (extension)',
    kind: 'file',
    apply({ dryRun }) {
      const body = [
        `// ${SENTINEL} — generated by \`guards install pi\`. Delete this file to uninstall.`,
        `import { createExtension } from ${JSON.stringify(PI_ENTRY)};`,
        '',
        'export default createExtension();',
        '',
      ].join('\n');
      if (dryRun) return body;
      fs.mkdirSync(path.dirname(PATHS.pi), { recursive: true });
      fs.writeFileSync(PATHS.pi, body);
      return body;
    },
  },

  omp: {
    label: 'omp (extension)',
    kind: 'file',
    apply({ dryRun }) {
      // omp loads the same `tool_call` API as pi; only the file extension differs.
      const body = [
        `// ${SENTINEL} — generated by \`guards install omp\`. Delete this file to uninstall.`,
        `import { createExtension } from ${JSON.stringify(PI_ENTRY)};`,
        '',
        'export default createExtension();',
        '',
      ].join('\n');
      if (dryRun) return body;
      fs.mkdirSync(path.dirname(PATHS.omp), { recursive: true });
      fs.writeFileSync(PATHS.omp, body);
      return body;
    },
  },

  claude: {
    label: 'Claude Code (PreToolUse hook)',
    kind: 'merge',
    event: 'PreToolUse',
    preview() { return JSON.stringify(guardsGroup('claude'), null, 2); },
    apply({ dryRun }) {
      const settings = readJson(PATHS.claude, {});
      const groups = (settings.hooks ??= {}).PreToolUse ?? [];
      const entry = { type: 'command', command: hookCommand('claude'), timeout: 10 };
      const existing = groups.findIndex((g) => isOurs(g));
      if (existing >= 0) groups[existing] = { ...groups[existing], matcher: '*', hooks: [entry] };
      else groups.push({ matcher: '*', hooks: [entry] });
      settings.hooks.PreToolUse = groups;
      return writeJson(PATHS.claude, settings, { dryRun });
    },
    remove({ dryRun }) {
      const settings = readJson(PATHS.claude, null);
      if (!settings?.hooks?.PreToolUse) return 'nothing to remove';
      settings.hooks.PreToolUse = settings.hooks.PreToolUse.filter((g) => !isOurs(g));
      return writeJson(PATHS.claude, settings, { dryRun });
    },
  },

  gemini: {
    label: 'Gemini CLI (BeforeTool hook)',
    kind: 'merge',
    event: 'BeforeTool',
    preview() { return JSON.stringify(guardsGroup('gemini'), null, 2); },
    apply({ dryRun }) {
      const settings = readJson(PATHS.gemini, {});
      const groups = (settings.hooks ??= {}).BeforeTool ?? [];
      const entry = { type: 'command', command: hookCommand('gemini'), timeout: 10 };
      const existing = groups.findIndex((g) => isOurs(g));
      if (existing >= 0) groups[existing] = { ...groups[existing], hooks: [entry] };
      else groups.push({ hooks: [entry] });
      settings.hooks.BeforeTool = groups;
      return writeJson(PATHS.gemini, settings, { dryRun });
    },
    remove({ dryRun }) {
      const settings = readJson(PATHS.gemini, null);
      if (!settings?.hooks?.BeforeTool) return 'nothing to remove';
      settings.hooks.BeforeTool = settings.hooks.BeforeTool.filter((g) => !isOurs(g));
      return writeJson(PATHS.gemini, settings, { dryRun });
    },
  },

  copilot: {
    label: 'Copilot CLI (preToolUse hook)',
    kind: 'file',
    apply({ dryRun }) {
      // Copilot owns this file exclusively, so we write it whole. `exec` runs the
      // binary directly — no shell, no quoting games.
      const body = {
        version: 1,
        hooks: {
          preToolUse: [{
            type: 'command',
            exec: process.execPath,
            args: [HOOK_ENTRY, '--harness', 'copilot'],
            timeoutSec: 10,
          }],
        },
      };
      const text = JSON.stringify(body, null, 2) + '\n';
      if (dryRun) return text;
      fs.mkdirSync(path.dirname(PATHS.copilot), { recursive: true });
      fs.writeFileSync(PATHS.copilot, text);
      return text;
    },
  },

  agy: {
    label: 'Antigravity CLI / agy (PreToolUse hook)',
    kind: 'file',
    // ~/.gemini/config/hooks.json is shared with other tools, so presence of the
    // file proves nothing: our own key has to be in it.
    isInstalled: () => Boolean(readJson(PATHS.agy, {})[SENTINEL]),
    // The file is shared with every other tool that registers an Antigravity
    // hook, so uninstalling removes our key and leaves the rest untouched.
    remove({ dryRun }) {
      const file = PATHS.agy;
      const all = readJson(file, null);
      if (!all || !all[SENTINEL]) return 'nothing to remove';
      delete all[SENTINEL];
      const text = JSON.stringify(all, null, 2) + '\n';
      if (dryRun) return text;
      if (Object.keys(all).length === 0) fs.rmSync(file);
      else fs.writeFileSync(file, text);
      return text;
    },
    preview: () => JSON.stringify({ [SENTINEL]: agyHookDefinition() }, null, 2),
    apply({ dryRun }) {
      // Antigravity keys hooks by name, so merging is one object key.
      const file = PATHS.agy;
      const all = readJson(file, {});
      all[SENTINEL] = agyHookDefinition();
      const text = JSON.stringify(all, null, 2) + '\n';
      if (dryRun) return text;
      fs.mkdirSync(path.dirname(file), { recursive: true });
      if (fs.existsSync(file)) fs.copyFileSync(file, `${file}.bak`);
      fs.writeFileSync(file, text);
      return text;
    },
  },
};

function installed(harness) {
  const installer = INSTALLERS[harness];
  if (!installer) return false;
  if (installer.isInstalled) return installer.isInstalled();
  if (installer.kind === 'file') return fs.existsSync(PATHS[harness]);
  const settings = readJson(PATHS[harness], {});
  const groups = settings?.hooks?.[installer.event] ?? [];
  return groups.some((g) => isOurs(g));
}

// --- commands ---------------------------------------------------------------

function cmdInit(argv) {
  const file = defaultConfigPath();
  const dryRun = argv.includes('--dry-run');
  if (fs.existsSync(file) && !argv.includes('--force')) {
    console.log(`rules already exist: ${file} (use --force to overwrite)`);
    return 0;
  }
  const text = STARTER_RULES;
  if (dryRun) { console.log(text); return 0; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote ${file} (${loadConfig(file).rules.length} rules)`);
  return 0;
}

function namedTargets(argv) {
  return [...new Set(argv.filter((a) => !a.startsWith('-') && HARNESSES.includes(normalizeName(a))).map(normalizeName))];
}

/**
 * What to install into, in order of preference:
 *   1. names on the command line — always honoured, never a prompt
 *   2. --all — every harness, present or not
 *   3. a checkbox pre-filled with what is actually installed
 *   4. no terminal: the detected ones, and say which ones out loud
 */
async function resolveTargets(argv) {
  const named = namedTargets(argv);
  if (named.length) return named;
  if (argv.includes('--all')) return [...HARNESSES];

  const found = detectAll();
  const present = found.filter((d) => d.present);
  if (!present.length) {
    console.log('nenhuma harness encontrada nesta máquina.');
    console.log('nomeie na mão: guards install claude gemini   (ou --all para todas)');
    return [];
  }
  if (!process.stdin.isTTY) {
    console.log('harness detectadas: ' + present.map((d) => d.harness).join(', '));
    return present.map((d) => d.harness);
  }
  const { selectHarnesses } = await import('./tui.js');
  const chosen = await selectHarnesses(found);
  if (!chosen) {
    console.log('cancelado — nada foi escrito.');
    return [];
  }
  if (!chosen.length) {
    console.log('nenhuma marcada — nada foi escrito.');
    return [];
  }
  return chosen;
}

async function cmdInstall(argv) {
  const dryRun = argv.includes('--dry-run');
  // A dry run never prompts: show what an interactive install would choose.
  const list = dryRun && !namedTargets(argv).length && !argv.includes('--all')
    ? detectAll().filter((d) => d.present).map((d) => d.harness)
    : await resolveTargets(argv);
  for (const harness of list) {
    const installer = INSTALLERS[harness];
    if (!installer) { console.log(`${harness}: unknown harness`); continue; }
    // A merge touches a shared settings file, so a dry run shows only our entry.
    const out = dryRun && installer.preview ? installer.preview() : installer.apply({ dryRun });
    if (dryRun) console.log(`--- ${harness} → ${PATHS[harness]} ---\n${out}`);
    else console.log(`✓ ${harness.padEnd(8)} ${installer.label}\n            ${PATHS[harness]}`);
  }
  if (dryRun) return 0;
  const configFile = defaultConfigPath();
  if (!fs.existsSync(configFile)) console.log(`\nno rules yet — run \`guards init\` (${configFile})`);
  return 0;
}

async function cmdUninstall(argv) {
  const dryRun = argv.includes('--dry-run');
  for (const harness of await resolveTargets(argv)) {
    const installer = INSTALLERS[harness];
    if (!installer) continue;
    if (installer.remove) {
      const done = installer.remove({ dryRun });
      if (done === 'nothing to remove') console.log(`· ${harness}: nothing installed`);
      else console.log(`✓ ${harness}: entry removed`);
      continue;
    }
    const file = PATHS[harness];
    if (fs.existsSync(file)) {
      if (!dryRun) fs.rmSync(file);
      console.log(`✓ ${harness}: ${file} deleted`);
    } else {
      console.log(`· ${harness}: nothing installed`);
    }
  }
  return 0;
}

function cmdStatus() {
  const config = loadConfig();
  console.log(`rules: ${config.rules.length} from ${config.file}${config.missing ? ' (file not created yet)' : ''}\n`);
  const found = new Map(detectAll().map((d) => [d.harness, d]));
  for (const harness of HARNESSES) {
    const on = installed(harness);
    const d = found.get(harness);
    const mark = on ? GREEN + '✓' + RESET : DIM + '·' + RESET;
    const seen = d.present
      ? DIM + (d.via === 'binario' ? d.binary : d.configDir) + RESET
      : DIM + 'não encontrada' + RESET;
    console.log(`${mark} ${harness.padEnd(8)} ${(INSTALLERS[harness]?.label ?? '').padEnd(40)} ${seen}`);
  }
  return 0;
}

function cmdRules() {
  const config = loadConfig();
  if (!config.rules.length) { console.log(`no rules loaded from ${config.file}`); return 0; }
  for (const rule of config.rules) {
    const tools = rule.tools ? rule.tools.join(', ') : 'any tool';
    const span = snapshot(config.file).rules.find((s) => s.id === rule.id);
    const mark = span && !span.enabled ? 'off' : (rule.action ?? 'deny');
    console.log(`${mark.padEnd(5)} ${rule.id.padEnd(24)} [${tools}] ${rule.reason ?? ''}`);
  }
  return 0;
}

function argAfter(argv, flag) {
  const i = argv.indexOf(flag);
  return i >= 0 ? argv[i + 1] : undefined;
}

async function cmdCheck(argv) {
  const harness = normalizeName(argAfter(argv, '--harness') ?? 'claude');
  let payload = {};
  const file = argAfter(argv, '--payload');
  if (file) {
    payload = JSON.parse(fs.readFileSync(file, 'utf8'));
  } else if (!process.stdin.isTTY) {
    const chunks = [];
    for await (const c of process.stdin) chunks.push(c);
    const text = Buffer.concat(chunks).toString('utf8').trim();
    if (text) payload = JSON.parse(text);
  }
  const tool = argAfter(argv, '--tool');
  if (tool) payload = { ...payload, tool_name: tool, toolName: tool };
  const argsJson = argAfter(argv, '--args');
  if (argsJson) {
    const args = JSON.parse(argsJson);
    payload = { ...payload, tool_input: args, toolArgs: args };
  }

  const adapter = await import(`./adapters/${harness}.js`);
  const config = loadConfig();
  const decision = evaluate({ harness, ...adapter.parse(payload) }, config);
  const r = decision.request;
  console.log(`harness  ${harness}`);
  console.log(`tool     ${r.rawTool} -> ${r.tool}`);
  console.log(`args     ${JSON.stringify(r.args)}`);
  console.log(`verdict  ${decision.action.toUpperCase()}${decision.ruleId ? ` (${decision.ruleId})` : ''}`);
  if (decision.reason) console.log(`reason   ${decision.reason}`);
  return decision.action === 'deny' ? 3 : 0;
}

function cmdToggle(argv, on) {
  const file = defaultConfigPath();
  const id = argv.find((a) => !a.startsWith('-'));
  if (!id) { console.log('uso: guards enable|disable <id>'); return 64; }
  const before = snapshot(file).rules.find((r) => r.id === id);
  if (!before) { console.log(`regra "${id}" não existe — veja a lista com: guards rules`); return 1; }
  if (before.enabled === on) { console.log(`${id} já está ${on ? 'ligada' : 'desligada'}`); return 0; }
  toggle(file, id);
  console.log(`✓ ${id} ${on ? 'ligada' : 'desligada'}`);
  return 0;
}

function cmdRm(argv) {
  const file = defaultConfigPath();
  const id = argv.find((a) => !a.startsWith('-'));
  if (!id) { console.log('uso: guards rm <id>'); return 64; }
  remove(file, id);
  console.log(`✓ ${id} removida`);
  return 0;
}

function cmdAdd(argv) {
  const file = defaultConfigPath();
  const get = (flag) => argAfter(argv, flag);
  const templateKey = get('--kind') ?? 'command';
  const value = get('--value');
  if (!value && templateKey !== 'custom') {
    console.log("uso: guards add --kind <command|path|text|custom> --value <padrao> [--id <nome>] [--reason <texto>]");
    return 64;
  }
  const rule = buildRule({ id: get('--id'), templateKey, value, reason: get('--reason'), templateText: value });
  add(file, rule);
  console.log(`✓ ${rule.id} criada — ${describeRule(rule)}`);
  return 0;
}

const USAGE = `guards — one guard engine for pi, omp, Claude Code, Copilot CLI, Gemini CLI and agy

  guards init [--force]            write a starter rule set
  guards install [harness...]      detect what is installed, pick, install
  guards uninstall [harness...]      same picker, to remove
  guards status                    which harnesses are guarded
  guards rules                     list loaded rules
  guards manage                    the guard menu (also /guards manage inside pi and omp)
  guards enable|disable <id>       turn one guard on or off
  guards rm <id>                   delete one guard
  guards add --kind command --value '<regex>' [--id x] [--reason '...']
  guards check --harness X --tool T --args '{...}'

  flags: --all (skip the picker), --dry-run, --force, --harness, --tool, --args, --payload
  env:   GUARDS_CONFIG (rules file), GUARDS_LOG=1 (trace to stderr)
`;

async function main(argv) {
  const [command = 'status', ...rest] = argv;
  switch (command) {
    case 'init': return cmdInit(rest);
    case 'install': return await cmdInstall(rest);
    case 'uninstall': case 'remove': return await cmdUninstall(rest);
    case 'status': return cmdStatus();
    case 'rules': case 'test': return cmdRules();
    case 'manage': case 'ui': {
      const { runManage } = await import('./tui.js');
      return await runManage(defaultConfigPath());
    }
    case 'enable': return cmdToggle(rest, true);
    case 'disable': return cmdToggle(rest, false);
    case 'rm': case 'remove-rule': return cmdRm(rest);
    case 'add': case 'new': return cmdAdd(rest);
    case 'check': return await cmdCheck(rest);
    case 'help': case '--help': case '-h': console.log(USAGE); return 0;
    default: console.log(USAGE); return 64;
  }
}

main(process.argv.slice(2))
  .then((code) => process.exit(code ?? 0))
  .catch((e) => { console.error(`guards: ${e.message}`); process.exit(1); });